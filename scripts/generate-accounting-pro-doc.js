// Helpers
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1, alignment: AlignmentType.RIGHT,
    spacing: { before: 400, after: 200, line: 360 },
    children: [new TextRun({ text, bold: true, size: 36, color: c(P.primary), font: { ascii: "Cairo", eastAsia: "Cairo" } })]
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2, alignment: AlignmentType.RIGHT,
    spacing: { before: 300, after: 150, line: 340 },
    children: [new TextRun({ text, bold: true, size: 30, color: c(P.accent), font: { ascii: "Cairo", eastAsia: "Cairo" } })]
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3, alignment: AlignmentType.RIGHT,
    spacing: { before: 240, after: 120, line: 320 },
    children: [new TextRun({ text, bold: true, size: 26, color: c(P.body), font: { ascii: "Cairo", eastAsia: "Cairo" } })]
  });
}
function p(text, opts = {}) {
  return new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { after: 160, line: 360 },
    indent: opts.noIndent ? {} : { firstLine: 480 },
    children: [new TextRun({ text: text || "", size: 24, color: c(P.body), font: { ascii: "Cairo", eastAsia: "Cairo" } })]
  });
}
function bul(text) {
  return new Paragraph({
    numbering: { reference: "bullets", level: 0 }, alignment: AlignmentType.RIGHT,
    spacing: { after: 100, line: 340 },
    children: [new TextRun({ text, size: 24, color: c(P.body), font: { ascii: "Cairo", eastAsia: "Cairo" } })]
  });
}
function tbl(headers, rows, widths) {
  const hr = new TableRow({ tableHeader: true, cantSplit: true, children: headers.map((h, i) => new TableCell({
    width: { size: widths[i], type: WidthType.PERCENTAGE },
    shading: { type: ShadingType.CLEAR, fill: c(P.primary) },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: h, bold: true, size: 22, color: "FFFFFF", font: { ascii: "Cairo", eastAsia: "Cairo" } })] })]
  }))});
  const drs = rows.map((row, ri) => new TableRow({ cantSplit: true, children: row.map((cell, ci) => new TableCell({
    width: { size: widths[ci], type: WidthType.PERCENTAGE },
    shading: { type: ShadingType.CLEAR, fill: ri % 2 === 0 ? "FFFFFF" : c(P.bg) },
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ alignment: AlignmentType.RIGHT, children: [new TextRun({ text: cell || "", size: 21, color: c(P.body), font: { ascii: "Cairo", eastAsia: "Cairo" } })] })]
  }))}));
  return new Table({ width: { size: 100, type: WidthType.PERCENTAGE }, borders: { top: { style: BorderStyle.SINGLE, size: 1, color: c(P.accent) }, bottom: { style: BorderStyle.SINGLE, size: 1, color: c(P.accent) }, left: { style: BorderStyle.NONE }, right: { style: BorderStyle.NONE }, insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: "DDDDDD" }, insideVertical: { style: BorderStyle.SINGLE, size: 1, color: "DDDDDD" } }, rows: [hr, ...drs] });
}

